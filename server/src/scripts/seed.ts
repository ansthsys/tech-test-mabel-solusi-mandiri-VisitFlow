function toVisitPlan(activity: SeedActivity): NewVisitPlan {
	const entity = seedEntities.find((item) => item.id === activity.entityUuid);

	if (!entity) {
		throw new Error(`Seed entity not found for activity ${activity.id}`);
	}

	return {
		id: activity.id,
		entityId: generateEntityId(entity),
		entityName: entity.name,
		entityType: entity.type,
		segment: entity.segment,
		entityRegion: entity.region,
		visitDate: activity.visitDate,
		status: activity.status,
		salesName: activity.salesName ?? null,
	};
}

async function seed() {
	appLogger.info('[SEED] Starting database seeding...');

	try {
		appLogger.info('[SEED] Check admin account already created...');
		const [adminExists] = await db.select().from(user).where(eq(user.email, 'admin@email.com'));

		if (!adminExists) {
			appLogger.info('[SEED] Creating admin account...');
			const { user: userCreated } = await auth.api.signUpEmail({
				body: {
					name: 'Admin',
					email: 'admin@email.com',
					password: 'Admin123!',
				},
			});

			if (userCreated) {
				appLogger.info('[SEED] Verifying admin account...');
				await db
					.update(user)
					.set({
						emailVerified: true,
					})
					.where(eq(user.id, userCreated.id));
			}
		}

		appLogger.info(`[SEED] Upserting ${seedEntities.length} entities...`);
		await db
			.insert(entities)
			.values(seedEntities)
			.onConflictDoUpdate({
				target: entities.id,
				set: {
					name: sql`excluded.name`,
					type: sql`excluded.type`,
					segment: sql`excluded.segment`,
					region: sql`excluded.region`,
					updatedAt: sql`now()`,
				},
			});

		const visitPlansPayload = seedActivities.map(toVisitPlan);

		appLogger.info(`[SEED] Upserting ${visitPlansPayload.length} activities...`);
		await db
			.insert(visitPlans)
			.values(visitPlansPayload)
			.onConflictDoUpdate({
				target: visitPlans.id,
				set: {
					entityId: sql`excluded.entity_id`,
					entityName: sql`excluded.entity_name`,
					entityType: sql`excluded.entity_type`,
					segment: sql`excluded.segment`,
					entityRegion: sql`excluded.entity_region`,
					visitDate: sql`excluded.visit_date`,
					status: sql`excluded.status`,
					salesName: sql`excluded.sales_name`,
					updatedAt: sql`now()`,
				},
			});

		appLogger.info('[SEED] Database seeding completed successfully');
	} catch (error) {
		appLogger.error({ error }, '[SEED] Seeding failed');
		throw error;
	} finally {
		process.exit(0);
	}
}

seed();
