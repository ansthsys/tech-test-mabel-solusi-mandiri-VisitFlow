/**
 * Mirrors the composite entityId generated by the visit-plans service:
 * name-type-segment-region with spaces removed.
 */
const generateEntityId = (entity: SeedEntity) =>
	[entity.name, entity.type, entity.segment, entity.region]
		.map((value) => value.replaceAll(' ', ''))
		.join('-');

